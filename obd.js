  const FIX = { O: '0', Q: '0', D: '0', I: '1', L: '1', T: '1', S: '5', Z: '2', B: '8', G: '6' };
  function parseCodes(text) {
    const out = [], seen = new Set();
    // русский распознаватель путает латинскую букву кода с кириллицей: Ы11230 → U11230, В1479 → B1479
    const lines = String(text || '').replace(/(^|[^A-Za-zА-Яа-яЁё])([ЫЦИUВBРPСC])(?=\s?[0-3][0-9A-F]{3})/g, (m, a, l) => a + ({ Ы: 'U', Ц: 'U', И: 'U', В: 'B', Р: 'P', С: 'C' }[l] || l)).split(/\n+/);
    lines.forEach((ln, i) => {
      // VW/Audi и другие пишут 7 знаков: U112300 = код U1123 + тип неисправности 00 (бывает перенос: «U11230» и «0» строкой ниже)
      const re = /([PCBU])\s?([0-3OoIlZzSs])([0-9A-Fa-fOoIlSsZzBGgDQqT]{3})(?:[0-9A-Fa-fOo]{1,2})?(?![0-9A-Za-z])/g;
      let m;
      while ((m = re.exec(ln))) {
        const body = (m[2] + m[3]).toUpperCase();
        // первая позиция после буквы всегда цифра 0–3, остальные могут быть A–F
        const fixed = body.split('').map((ch, j) => (j < 1 || !/[A-F]/.test(ch)) ? (FIX[ch] || ch) : ch).join('');
        if (!/^[0-3][0-9A-F]{3}$/.test(fixed)) continue;
        const c = m[1] + fixed;
        if (seen.has(c)) continue; seen.add(c);
        let desc = (ln.slice(m.index + m[0].length) || '').replace(/^[\s:\-–—.]*(?:[0-9A-F]{2}(?![A-Za-z]))?[\s:\-–—.]*/, '').replace(/[^A-Za-zА-Яа-яЁё0-9 /().,'-]/g, ' ').replace(/\s+/g, ' ').trim();
        const okD = t => t.length >= 8 && !/пассив|спорад|активн|статич|current|history|pending|^\d+\s|fault|system/i.test(t);
        const cl = t => String(t || '').replace(/^\s*[0-9A-F]{1,2}\s+/, '').replace(/[^A-Za-zА-Яа-яЁё0-9 /().,'-]/g, ' ').replace(/\s+/g, ' ').trim();
        if (!okD(desc)) { const nx = cl(lines[i + 1]), pv = cl(lines[i - 1]); const isCode = t => /[PCBU]\s?[0-3O][0-9A-FO]{3}/i.test(t); desc = (lines[i + 1] && !isCode(lines[i + 1]) && okD(nx)) ? nx : (lines[i - 1] && !isCode(lines[i - 1]) && okD(pv)) ? pv : desc; }
        re.lastIndex = m.index + m[0].length;
        let ctx = ln; for (let j = i + 1; j < Math.min(lines.length, i + 4) && !/[PCBU]\s?[0-3O][0-9A-FO]{3}/i.test(lines[j]); j++) ctx += ' ' + lines[j]; ctx = ctx.toLowerCase();
        const st = /histor|stored|memory|пассив|спорад|сохран/.test(ctx) ? 'h' : /pending|ожида/.test(ctx) ? 'p' : /permanent|постоян/.test(ctx) ? 'perm' : /current|active|confirmed|активн|статич|текущ/.test(ctx) ? 'c' : '';
        out.push({ c, d: desc.slice(0, 90), st });
      }
    });
    return out;
  }

