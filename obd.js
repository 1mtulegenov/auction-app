  // список проблем из отчёта ThinkCar без кодов: «Есть 6 проблемы для …» и пункты «1,…», «2,…».
  // Разделы «Inspections are normal / нормально» пропускаются: там исправные блоки.
  function parseText(text) {
    const out = [], lines = String(text || '').split(/\n+/).map(l => l.trim()).filter(Boolean);
    let on = false, cur = null;
    const push = () => { if (cur) { const d = cur.replace(/\s+/g, ' ').replace(/[|_~«»"]+/g, '').trim(); if (d.length > 6) out.push({ c: '', d: d.slice(0, 140), st: '' }); } cur = null; };
    for (const ln of lines) {
      if (/(есть|обнаруж\S*)\s*\d*\s*(проблем|неисправ|ошиб)|\d+\s*(проблем|неисправ)|problem|fault code|dtc/i.test(ln) && !/normal|норм|исправн\S*\s+нет/i.test(ln)) { push(); on = true; continue; }
      if (/inspections? are normal|normal for|в норме|нормально|без ошибок|no fault|no dtc/i.test(ln)) { push(); on = false; continue; }
      if (!on) continue;
      const m = ln.match(/^\s*\d{1,2}\s*[,.)]\s*(.*)$/);
      if (m) { push(); cur = m[1]; }
      else if (cur != null) cur += ' ' + ln;
    }
    push();
    return out;
  }
  function parse(text) {
    const codes = parseCodes(text);
    const seen = new Set(codes.map(c => c.c));
    // описания без кода, если кода в этой же строке нет
    parseText(text).forEach(t => { if (![...seen].some(c => t.d.includes(c))) codes.push(t); });
    return codes;
  }
  // итог по машине: самая высокая критичность и короткий совет
  function verdict(codes) {
    if (!codes || !codes.length) return null;
    const arr = codes.map(x => info(x.c, x.d));
    const act = arr.filter((a, i) => codes[i].st !== 'h');
    const top = Math.max(...(act.length ? act : arr).map(a => a.s));
    const n3 = arr.filter(a => a.s === 3).length;
    const tx = top === 3 ? (n3 > 1 ? n3 + ' серьёзные ошибки' : 'Есть серьёзная ошибка') + ': брать только с большим дисконтом или пропустить'
      : top === 2 ? 'Средний ремонт: заложить в ставку' : 'Мелочи: на цену почти не влияют';
    const h3 = top < 3 && arr.some((a, i) => a.s === 3 && codes[i].st === 'h');
    return { s: top, t: tx + (h3 ? '. Есть сохранённая серьёзная ошибка: спросить или проверить' : '') };
  }
  const SEV = { 3: ['bad', 'серьёзно'], 2: ['warn', 'средне'], 1: ['ok', 'мелочь'] };
  const ST = { h: 'сохранённая', p: 'ожидающая', perm: 'постоянная', c: 'текущая' };
  return { info, parse, verdict, norm, SEV, ST, size: Object.keys(D).length };
